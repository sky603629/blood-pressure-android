// Browser regression against an isolated preview database, never the family service.
// NODE_PATH must include the test environment's Playwright package directory.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.BP_PREVIEW_URL || 'http://127.0.0.1:8765';
const key = process.env.BP_PREVIEW_KEY || 'preview-key-123';
const output = path.resolve(__dirname, '../../build/ui-qa');
fs.mkdirSync(output, { recursive: true });
const headers = { Authorization: 'Bearer ' + key };
const api = async endpoint => {const r=await fetch(base+endpoint,{headers});assert.equal(r.status,200);return r.json();};

(async () => {
  const browser = await chromium.launch({headless:true,channel:'chrome'});
  const context = await browser.newContext({viewport:{width:1440,height:1000},locale:'zh-CN',timezoneId:'Asia/Shanghai'});
  const page=await context.newPage(), errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',msg=>{if(msg.type()==='error' && !msg.text().includes('503'))errors.push(msg.text());});
  const idle=()=>page.waitForSelector('#records-panel[aria-busy="false"]',{state:'attached'});
  const click=async selector=>{await page.locator(selector).click();await idle();};
  try {
    await page.goto(base);await page.screenshot({path:path.join(output,'login-desktop.png')});
    assert.equal(await page.locator('#records-panel').isVisible(),false);
    await page.locator('#key').fill(key);await page.locator('#key').press('Enter');await idle();
    assert.equal(await page.locator('#login').isVisible(),false);
    const mom=await page.locator('#member').inputValue();
    assert(mom,'default selects a single member');
    assert.equal(await page.locator('#records .timeline-record').count(),20);
    assert.equal(await page.locator('#stat1-label').innerText(),'平均高压');
    await page.waitForTimeout(180);await page.screenshot({path:path.join(output,'dashboard-desktop.png')});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'desktop fits');
    await click('[data-range="all"]');
    const all=await api('/api/v1/overview?device_id='+mom);
    assert.equal(await page.locator('#count').innerText(),'共 '+all.summary.count+' 条');
    assert.equal(await page.locator('#stat1-value').innerText(),all.summary.systolic.toFixed(1).replace(/\.0$/,''));
    const summary=await page.locator('#stat1-value').innerText();
    await click('#next');assert((await page.locator('#page').innerText()).includes('第 21–40'));
    assert.equal(await page.locator('#stat1-value').innerText(),summary,'pagination never changes full-range averages');
    await click('#previous');
    await click('#point-previous');const before=await page.locator('#chart-detail').innerText();
    await page.locator('#chart-scroll').focus();await page.keyboard.press('ArrowLeft');
    assert.notEqual(await page.locator('#chart-detail').innerText(),before,'keyboard point navigation');
    const priorScroll=await page.locator('#chart-scroll').evaluate(e=>e.scrollLeft);
    await page.locator('#chart-scroll').evaluate(e=>e.scrollLeft=0);
    assert(priorScroll>0,'long curves scroll horizontally');
    await click('#reading-mode');assert.equal(await page.locator('#daily-mode').getAttribute('aria-pressed'),'false');
    assert((await page.locator('#chart-detail').innerText()).includes('脉搏'));
    await page.locator('#chart-metric').selectOption('pulse');
    assert((await page.locator('#chart-legend').innerText()).includes('脉搏'));
    await page.locator('#chart-metric').selectOption('pressure');
    await click('#daily-mode');
    await click('#member-list button[data-member=""]');
    assert.equal(await page.locator('#stat1-label').innerText(),'测量次数','families are not averaged together');
    assert((await page.locator('#chart-legend').innerText()).includes('老妈手机'));
    assert((await page.locator('#chart-legend').innerText()).includes('老爸手机'));
    await page.locator('#member').selectOption(mom);await idle();
    const first=all.daily[10].date,last=all.daily[15].date;
    await page.locator('#start').fill(first);await page.locator('#end').fill(last);await click('#refresh');
    const expected=await api('/api/v1/overview?device_id='+mom+'&from_ms='+Date.parse(first+'T00:00:00+08:00')+'&to_ms='+(Date.parse(last+'T00:00:00+08:00')+86400000));
    assert.equal(await page.locator('#count').innerText(),'共 '+expected.summary.count+' 条');
    await click('#records .record-detail >> nth=0');
    assert.equal(await page.locator('#record-dialog').isVisible(),true);
    await page.keyboard.press('Escape');assert.equal(await page.locator('#record-dialog').isVisible(),false);
    await page.locator('#start').fill('2020-01-01');await page.locator('#end').fill('2020-01-02');await click('#refresh');
    assert.equal(await page.locator('#chart-empty').isVisible(),true);
    assert.equal(await page.locator('#stat1-value').innerText(),'—');
    await click('[data-range="30"]');
    await page.route('**/api/v1/overview?**',route=>route.fulfill({status:503,contentType:'application/json',body:'{}'}));
    await click('#reload');assert.equal(await page.locator('#records .timeline-record').count(),20,'temporary failure retains old UI');
    assert.equal(await page.locator('#message').isVisible(),true);await page.unroute('**/api/v1/overview?**');
    await click('#reload');
    const downloadWait=page.waitForEvent('download');await click('#export');const download=await downloadWait;
    assert.equal(download.suggestedFilename(),'家人的血压记录.csv');
    await page.route('**/api/v1/measurements?**',async route=>{
      const response=await route.fetch(),data=await response.json();
      if(data.records.length)data.records[0].note='<img src=x onerror="window.previewXss=true"> <script>window.previewXss=true</script>';
      await route.fulfill({response,json:data});
    });
    await click('#reload');await click('#records .record-detail >> nth=0');
    assert((await page.locator('#record-details').innerText()).includes('<img'));
    assert.equal(await page.locator('#record-details img, #record-details script').count(),0);
    assert.equal(await page.evaluate(()=>window.previewXss),undefined,'notes render only as text');
    await click('#close-dialog');await page.unroute('**/api/v1/measurements?**');await click('#reload');
    const visibleInputs=()=>page.locator('#settings-members input');
    const setVisible=async ids=>{for(const checkbox of await visibleInputs().all())await checkbox.setChecked(ids.includes(await checkbox.inputValue()));};
    const preferenceKey='pressure-diary.display.v1';
    await click('#settings');await setVisible([]);await page.locator('#save-settings').click();
    assert((await page.locator('#settings-error').innerText()).includes('至少选择一位'));
    await setVisible([mom]);await click('#save-settings');
    assert.equal(await page.locator('#settings-dialog').isVisible(),false);
    assert.equal(await page.locator('#member-list button').count(),1);
    assert.equal(await page.locator('#member option').count(),1);
    assert.equal(await page.locator('#member').inputValue(),mom);
    assert.equal(await page.locator('#member-list button[data-member=""]').count(),0,'one member automatically hides family aggregate');
    assert(!(await page.locator('#member-list').innerText()).includes('老爸手机'));
    const preference=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),preferenceKey);
    assert.deepEqual(preference.memberIds,[mom]);
    await page.reload();await page.locator('#key').fill(key);await page.locator('#key').press('Enter');await idle();
    assert.equal(await page.locator('#member-list button').count(),1,'selection survives reload and login');
    assert.equal(await page.locator('#member').inputValue(),mom);
    await click('[data-range="all"]');
    await click('#settings');await setVisible([]);await page.locator('#close-settings').click();
    assert.equal(await page.locator('#member-list button').count(),1,'cancel does not change preferences');
    const members=await api('/api/v1/devices'),empty=members.devices.find(d=>d.recordCount===0).id;
    await click('#settings');await setVisible([mom,empty]);await page.locator('#settings-show-all').check();
    await click('#save-settings');await click('#member-list button[data-member=""]');
    assert.equal(await page.locator('#member-list button').count(),3);
    const scoped=await api('/api/v1/overview?device_ids='+mom+'&device_ids='+empty);
    assert.equal(await page.locator('#count').innerText(),'共 '+scoped.summary.count+' 条','aggregate excludes hidden family');
    assert.equal(await page.locator('#stat1-value').innerText(),scoped.summary.systolic.toFixed(1).replace(/\.0$/,''));
    const csvResponse=page.waitForResponse(r=>r.url().includes('/api/v1/measurements.csv'));
    const scopedDownload=page.waitForEvent('download');await click('#export');await scopedDownload;
    assert(!(await (await csvResponse).text()).includes('老爸手机'),'CSV excludes hidden family');
    await click('#settings');await page.locator('#settings-show-all').uncheck();await click('#save-settings');
    assert.equal(await page.locator('#member-list button[data-member=""]').count(),0,'aggregate can be hidden independently');
    const savedPreference=await page.evaluate(key=>localStorage.getItem(key),preferenceKey);
    await click('#settings');await page.locator('#settings-reset').click();
    await page.route('**/api/v1/overview?**',route=>route.fulfill({status:503,contentType:'application/json',body:'{}'}));
    await click('#save-settings');assert(await page.locator('#settings-dialog').isVisible());
    assert.equal(await page.evaluate(key=>localStorage.getItem(key),preferenceKey),savedPreference,'failed save preserves settings');
    assert.equal(await page.locator('#member-list button').count(),2,'failed save restores navigation');
    await page.unroute('**/api/v1/overview?**');await click('#save-settings');
    assert.equal(await page.locator('#member-list button').count(),4,'restore-all restores family choices');
    await page.locator('#member').selectOption(mom);await idle();
    for(const width of [768,390,320]) {
      await page.setViewportSize({width,height:1000});await page.waitForTimeout(200);
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'viewport fits: '+width);
      await page.screenshot({path:path.join(output,'dashboard-'+width+'.png')});
      await page.locator('#history').scrollIntoViewIfNeeded();await page.screenshot({path:path.join(output,'records-'+width+'.png')});await page.evaluate(()=>window.scrollTo(0,0));
      assert.equal(await page.locator('#point-previous').isVisible(),true);
      await click('#settings');await page.screenshot({path:path.join(output,'settings-'+width+'.png')});
      assert.equal(await page.locator('#save-settings').isVisible(),true);await click('#close-settings');
    }
    await click('#records .record-detail >> nth=0');
    await page.screenshot({path:path.join(output,'record-mobile.png')});await click('#close-dialog');
    await page.locator('#logout').click();
    assert.equal(await page.locator('#login').isVisible(),true);
    assert.equal(await page.locator('#records .timeline-record').count(),0);
    assert.equal(await page.locator('#latest-pressure').innerText(),'—');
    assert.equal(await page.evaluate(()=>sessionStorage.length),0);
    assert.deepEqual(await page.evaluate(()=>Object.keys(localStorage)),[preferenceKey],'only display preferences are persisted');
    assert(!(await page.evaluate(()=>Object.values(localStorage).join(''))).includes(key),'viewing keys are never persisted');
    assert.deepEqual(errors,[],'no JS or CSP errors');
    console.log('PASS: desktop/mobile layouts, full-range statistics, chart navigation, filters, CSV, member display settings, persistence, cancellation, scoped aggregate/export, failed-save rollback and logout.');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
